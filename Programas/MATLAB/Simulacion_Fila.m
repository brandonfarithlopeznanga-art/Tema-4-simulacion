%% =========================================================
%       SIMULADOR VISUAL DE ATENCION DE CLIENTES
% ==========================================================

numClientes = 30;

% Generar datos aleatorios
tiempoLlegada = cumsum(randi([1 4],1,numClientes));
tiempoAtencion = randi([2 7],1,numClientes);

tiempoInicio = zeros(1,numClientes);
tiempoSalida = zeros(1,numClientes);
tiempoEspera = zeros(1,numClientes);

for i = 1:numClientes
    
    if i == 1
        tiempoInicio(i) = tiempoLlegada(i);
    else
        tiempoInicio(i) = max(tiempoLlegada(i), tiempoSalida(i-1));
    end
    
    tiempoEspera(i) = tiempoInicio(i) - tiempoLlegada(i);
    tiempoSalida(i) = tiempoInicio(i) + tiempoAtencion(i);
end

%% Estadisticas

promedioEspera = mean(tiempoEspera);
maxEspera = max(tiempoEspera);
tiempoTotal = max(tiempoSalida);

%% =========================================================
%                    VENTANA PRINCIPAL
% ==========================================================

